/**
 * @notice: Currently only supports op types defined in the IS_BASIC_CMP_OP macro, if there are requirements outside of this, please extend the implementation of this interface
 * */
inline ObItemType get_opposite_compare_type(ObItemType src_type)
{
  ObItemType ret_type = src_type;
  switch (src_type) {
    case T_OP_LT:
      ret_type = T_OP_GT;
      break;
    case T_OP_GT:
      ret_type = T_OP_LT;
      break;
    case T_OP_LE:
      ret_type = T_OP_GE;
      break;
    case T_OP_GE:
      ret_type = T_OP_LE;
      break;
    case T_OP_EXISTS:
      ret_type = T_OP_NOT_EXISTS;
      break;
    case T_OP_NOT_EXISTS:
      ret_type = T_OP_EXISTS;
      break;
    default:
      ret_type = src_type;
      break;
  }
  return ret_type;
}

