int ObTablePartitionInfo::assign(const ObTablePartitionInfo &other)
{
  int ret = OB_SUCCESS;
  table_access_plan_ = other.table_access_plan_;
  if (OB_FAIL(table_targets_.assign(other.table_targets_))) {
  }
  return ret;
}

int ObTablePartitionInfo::init_access_plan(ObSqlSchemaGuard &schema_guard,
                                              const ObDMLStmt &stmt,
                                              ObExecContext *exec_ctx,
                                              const ObIArray<ObRawExpr*> &filter_exprs,
                                              const uint64_t table_id,
                                              const uint64_t ref_table_id,
                                              const ObIArray<ObObjectID> *part_ids,
                                              const common::ObDataTypeCastParams &dtc_params,
                                              bool is_dml_table,
                                              ObIArray<ObRawExpr *> *sort_exprs)
{
  int ret = OB_SUCCESS;
  if (OB_SUCC(ret)) {
    if (OB_FAIL(table_access_plan_.init_access_plan(&schema_guard,
                                        stmt,
                                        exec_ctx,
                                        filter_exprs,
                                        table_id,
                                        ref_table_id,
                                        part_ids,
                                        dtc_params,
                                        is_dml_table,
                                        sort_exprs))) {
    }
  }
  return ret;
}

int ObTablePartitionInfo::get_not_insert_dml_part_sort_expr(const ObDMLStmt &stmt,
                                                            ObIArray<ObRawExpr*> *sort_exprs) const
{
  return table_access_plan_.get_not_insert_dml_part_sort_expr(stmt, sort_exprs);
}

int ObTablePartitionInfo::calculate_access_targets(
                          ObExecContext &exec_ctx,
                          const ParamStore &params,
                          const common::ObDataTypeCastParams &dtc_params)
{
  int ret = OB_SUCCESS;
  if (OB_FAIL(table_access_plan_.calculate_tablet_targets(
                       exec_ctx,
                       params,
                       table_targets_.get_tablets_for_update(),
                       dtc_params))) {
  } else {
    table_targets_.set_table_identity(
        table_access_plan_.get_table_id(), table_access_plan_.get_ref_table_id());
  }
  return ret;
}
//For the case of local index and lookup,
//because the TableAccessPlan generated by the optimizer retains the table_id of the main table,
//and the executor needs to calculate the tablet_id according to the table_id of the local index,
//the ref_table_id in the TableAccessPlan needs to be replaced eventually
int ObTablePartitionInfo::replace_access_source(ObExecContext &exec_ctx,
                                                     uint64_t ref_table_id,
                                                     bool is_local_index)
{
  int ret = OB_SUCCESS;
  bool is_das_dyn_prune_part = table_access_plan_.use_das() && table_access_plan_.get_has_dynamic_exec_param();
  if (table_access_plan_.get_ref_table_id() != ref_table_id) {
    if (is_local_index && !is_das_dyn_prune_part) {
      //only use to calc local index and main table related tablet info
      //for the local index lookup,
      //need to use the local index id as the table_id for partition calculation
      DASTableAccessMeta &access_meta = table_access_plan_.get_access_meta();
      DASRelatedTabletMap *related_map = nullptr;

      access_meta.related_table_ids_.reset();
      access_meta.related_table_ids_.set_capacity(1);
      ref_table_id = ref_table_id;
      if (OB_FAIL(access_meta.related_table_ids_.push_back(ref_table_id))) {
      } else if (OB_FAIL(TableAccessTargetBuilder::build_related_tablet_info(table_access_plan_, exec_ctx, related_map))) {
      } else if (OB_FAIL(table_targets_.replace_local_index_targets(*related_map, ref_table_id))) {
      } else if (OB_FAIL(table_access_plan_.replace_ref_table_id(ref_table_id, exec_ctx))) {
      }
      //need to clear the related info in access meta
      access_meta.related_table_ids_.reset();
      if (nullptr != related_map) {
        related_map->clear();
        related_map = nullptr;
      }
    } else {
      //get the real table access info use the real table id
      if (OB_FAIL(table_access_plan_.replace_ref_table_id(ref_table_id, exec_ctx))) {
      } else if (!is_das_dyn_prune_part) {
        table_targets_.set_table_identity(table_access_plan_.get_table_id(), ref_table_id);
      }
    }
    LOG_TRACE("replace final access info", K(table_access_plan_.get_access_meta()), K(ref_table_id), K(table_targets_));
  }
  return ret;
}

TableAccessShape ObTablePartitionInfo::get_access_shape() const
{
  const TabletAccessTargetIArray &tablet_targets =
      table_targets_.get_tablets();
  return table_access_plan_.get_access_shape(tablet_targets);
}

