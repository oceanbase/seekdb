#!/usr/bin/env python3
"""Helpers for running a local SeekDB instance on Windows.

The helper keeps every artifact inside a single "home" directory so that a
developer can run an instance without administrator rights and without
registering a Windows service:

    <home>/bin      seekdb.exe and the observer helpers
    <home>/etc      seekdb.cnf
    <home>/share    static resources shipped with the package
    <home>/store    data directory and redo log
    <home>/run      runtime files, including telemetry.json
    <home>/log      server log

Typical usage with an already unpacked package payload:

    python seekdb_windows.py layout --home D:\\seekdb_home --payload D:\\payload
    python seekdb_windows.py start  --home D:\\seekdb_home
    python seekdb_windows.py verify --home D:\\seekdb_home
    python seekdb_windows.py telemetry --home D:\\seekdb_home

The script only depends on the Python standard library.  The optional SQL
round-trip check in "verify" uses PyMySQL when it is importable and is skipped
otherwise.
"""

import argparse
import json
import os
import re
import socket
import subprocess
import sys
import time

DEFAULT_PORT = 2881
DEFAULT_MEMORY_LIMIT = "4G"
DEFAULT_CPU_COUNT = 8

# The observer writes a canonical RFC 9562 UUID (8-4-4-4-12) into
# <home>/run/telemetry.json.
TELEMETRY_UUID_RE = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"
)

CONFIG_TEMPLATE = """# SeekDB configuration file (generated by seekdb_windows.py)

# These parameters are permanently valid
base-dir={base_dir}
data-dir={data_dir}
redo-dir={redo_dir}

# These parameters are valid only during initialization
port={port}
cpu_count={cpu_count}
memory_limit={memory_limit}
"""


def log(message):
    print("[seekdb] {}".format(message), flush=True)


def ok(message):
    print("[seekdb][OK] {}".format(message), flush=True)


def warn(message):
    print("[seekdb][WARN] {}".format(message), flush=True)


def err(message):
    print("[seekdb][ERROR] {}".format(message), file=sys.stderr, flush=True)


def to_posix(path):
    """Convert a Windows path to the forward-slash form accepted by SeekDB."""
    return path.replace("\\", "/")


def telemetry_path(home):
    return os.path.join(home, "run", "telemetry.json")


def read_telemetry(home):
    """Return the parsed telemetry.json document, or None when unavailable."""
    path = telemetry_path(home)
    if not os.path.isfile(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, ValueError) as exc:
        warn("cannot read {}: {}".format(path, exc))
        return None


def telemetry_id(home):
    """Return the telemetry UUID recorded by the observer, or an empty string."""
    document = read_telemetry(home)
    if not document:
        return ""
    return (document.get("content") or {}).get("id", "") or ""


def make_junction(link, target):
    """Create a directory junction so that <home> can share the package files."""
    if os.path.exists(link):
        return True
    if shutil.which("cmd") is None:
        return False
    result = subprocess.call(
        ["cmd", "/c", "mklink", "/J", link, target],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    return result == 0


def do_layout(args):
    """Create the home directory and write a minimal seekdb.cnf."""
    home = os.path.abspath(args.home)
    payload = os.path.abspath(args.payload) if args.payload else None

    for name in ("etc", "store", "run", "log"):
        os.makedirs(os.path.join(home, name), exist_ok=True)

    if payload:
        for name in ("bin", "etc", "share"):
            source = os.path.join(payload, name)
            if not os.path.isdir(source):
                continue
            target = os.path.join(home, name)
            if os.path.exists(target):
                continue
            if make_junction(target, source):
                log("junction {} -> {}".format(target, source))
            else:
                log("copying {} -> {}".format(source, target))
                shutil.copytree(source, target)

    binary = os.path.join(home, "bin", "seekdb.exe")
    if not os.path.isfile(binary):
        err("seekdb.exe not found at {}".format(binary))
        err("pass --payload <dir> that contains bin/, etc/ and share/")
        return 1

    base_dir = to_posix(home)
    config = CONFIG_TEMPLATE.format(
        base_dir=base_dir,
        data_dir=base_dir + "/store",
        redo_dir=base_dir + "/store/redo",
        port=args.port,
        cpu_count=args.cpu_count,
        memory_limit=args.memory_limit,
    )
    config_path = os.path.join(home, "etc", "seekdb.cnf")
    with open(config_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(config)
    ok("configuration written to {}".format(config_path))
    return 0


def process_running():
    result = subprocess.run(
        ["tasklist", "/FI", "IMAGENAME eq seekdb.exe", "/NH"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    return "seekdb.exe" in (result.stdout or "")


def port_open(port, host="127.0.0.1"):
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(1.5)
        return sock.connect_ex((host, port)) == 0


def do_start(args):
    home = os.path.abspath(args.home)
    binary = os.path.join(home, "bin", "seekdb.exe")
    if not os.path.isfile(binary):
        err("seekdb.exe not found at {}".format(binary))
        return 1
    if process_running():
        ok("seekdb is already running")
        return do_status(args)

    log_file = os.path.join(home, "log", "seekdb.out.log")
    err_file = os.path.join(home, "log", "seekdb.err.log")
    os.makedirs(os.path.dirname(log_file), exist_ok=True)
    out_handle = open(log_file, "ab")
    err_handle = open(err_file, "ab")
    try:
        process = subprocess.Popen(
            [binary, "--base-dir={}".format(to_posix(home)), "--nodaemon"],
            cwd=os.path.join(home, "bin"),
            stdout=out_handle,
            stderr=err_handle,
            creationflags=getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0),
        )
    finally:
        out_handle.close()
        err_handle.close()

    log("seekdb started with pid {}, waiting for port {}".format(process.pid, args.port))
    deadline = time.time() + args.timeout
    while time.time() < deadline:
        time.sleep(2)
        if port_open(args.port):
            ok("seekdb is listening on 127.0.0.1:{}".format(args.port))
            return do_status(args)
        if process.poll() is not None:
            err("seekdb exited with code {}, see {}".format(process.returncode, err_file))
            return 1
    err("timed out while waiting for port {}".format(args.port))
    return 1


def do_stop(args):
    result = subprocess.run(
        ["taskkill", "/F", "/IM", "seekdb.exe"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if result.returncode == 0:
        ok("seekdb stopped")
    else:
        warn("seekdb was not running")
    return 0


def do_status(args):
    home = os.path.abspath(args.home)
    print("[seekdb] process : {}".format("running" if process_running() else "stopped"))
    print("[seekdb] port    : {}".format(
        "listening" if port_open(args.port) else "not listening"))
    identifier = telemetry_id(home)
    if identifier:
        print("[seekdb] telemetry UUID : {}".format(identifier))
    else:
        warn("no telemetry UUID yet ({})".format(telemetry_path(home)))
    return 0


def do_telemetry(args):
    home = os.path.abspath(args.home)
    identifier = telemetry_id(home)
    if not identifier:
        err("no telemetry UUID found in {}".format(telemetry_path(home)))
        return 1
    if not TELEMETRY_UUID_RE.match(identifier):
        warn("telemetry id is not a canonical UUID: {}".format(identifier))
        print(identifier)
        return 0
    print(identifier)
    return 0


def do_verify(args):
    """Check the files, the process, the port, SQL and the telemetry UUID."""
    home = os.path.abspath(args.home)
    failures = []

    required = [
        os.path.join(home, "bin", "seekdb.exe"),
        os.path.join(home, "etc", "seekdb.cnf"),
        os.path.join(home, "store"),
        os.path.join(home, "run", "telemetry.json"),
    ]
    for path in required:
        if os.path.exists(path):
            print("  [OK]   exists: {}".format(path))
        else:
            failures.append("missing file: {}".format(path))
            print("  [FAIL] missing: {}".format(path))

    if process_running():
        print("  [OK]   seekdb.exe is running")
    else:
        failures.append("seekdb.exe is not running")
        print("  [FAIL] seekdb.exe is not running")

    if port_open(args.port):
        print("  [OK]   port {} is listening".format(args.port))
    else:
        failures.append("port {} is not listening".format(args.port))
        print("  [FAIL] port {} is not listening".format(args.port))

    try:
        import pymysql
    except ImportError:
        warn("PyMySQL is not installed, skipping the SQL round-trip check")
    else:
        try:
            connection = pymysql.connect(
                host="127.0.0.1",
                port=args.port,
                user="root",
                password="",
                connect_timeout=10,
            )
            with connection.cursor() as cursor:
                cursor.execute("SELECT VERSION()")
                version = cursor.fetchone()[0]
            connection.close()
            print("  [OK]   SQL round-trip: VERSION()={}".format(version))
        except Exception as exc:  # noqa: BLE001
            failures.append("SQL round-trip failed: {}".format(exc))
            print("  [FAIL] SQL round-trip failed: {}".format(exc))

    identifier = telemetry_id(home)
    if identifier:
        if TELEMETRY_UUID_RE.match(identifier):
            print("  [OK]   telemetry UUID: {}".format(identifier))
        else:
            failures.append("telemetry id is not a canonical UUID: {}".format(identifier))
            print("  [FAIL] telemetry id is not a canonical UUID: {}".format(identifier))
    else:
        failures.append("no telemetry UUID in {}".format(telemetry_path(home)))
        print("  [FAIL] no telemetry UUID in {}".format(telemetry_path(home)))

    print()
    if failures:
        for failure in failures:
            err(failure)
        err("{} check(s) failed".format(len(failures)))
        return 1
    ok("all checks passed")
    return 0


def main():
    parser = argparse.ArgumentParser(
        description="Deploy and manage a local SeekDB instance on Windows")
    parser.add_argument("--home", required=True,
                        help="seekdb home directory holding bin/etc/store/run/log")
    parser.add_argument("--port", type=int, default=DEFAULT_PORT)
    parser.add_argument("--memory-limit", default=DEFAULT_MEMORY_LIMIT)
    parser.add_argument("--cpu-count", type=int, default=DEFAULT_CPU_COUNT)
    parser.add_argument("--timeout", type=int, default=240,
                        help="seconds to wait for the observer port")
    subparsers = parser.add_subparsers(dest="action", required=True)

    layout = subparsers.add_parser("layout", help="create the home directory")
    layout.add_argument("--payload",
                        help="unpacked package directory containing bin/, etc/ and share/")

    subparsers.add_parser("start", help="start the observer")
    subparsers.add_parser("stop", help="stop the observer")
    subparsers.add_parser("status", help="show process, port and telemetry UUID")
    subparsers.add_parser("telemetry", help="print the telemetry UUID")
    subparsers.add_parser("verify", help="run the deployment self-check")

    args = parser.parse_args()
    handlers = {
        "layout": do_layout,
        "start": do_start,
        "stop": do_stop,
        "status": do_status,
        "telemetry": do_telemetry,
        "verify": do_verify,
    }
    return handlers[args.action](args)


if __name__ == "__main__":
    sys.exit(main())
